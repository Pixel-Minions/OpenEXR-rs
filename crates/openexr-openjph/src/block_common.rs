use std::sync::OnceLock;

/// The decoding tables (`vlc_tbl0`, `vlc_tbl1`, `uvlc_tbl0`, `uvlc_tbl1`, `uvlc_tbl1_wide`,
/// `uvlc_bias`).
pub(crate) struct BlockTables {
    pub(crate) vlc_tbl0: [u16; 1024],
    pub(crate) vlc_tbl1: [u16; 1024],
    pub(crate) uvlc_tbl0: [u16; 256 + 64],
    pub(crate) uvlc_tbl1: [u16; 256],
    pub(crate) uvlc_tbl1_wide: Vec<u32>,
    pub(crate) uvlc_bias: [u8; 256 + 64],
}

/// The tables, built on first use.
pub(crate) fn tables() -> &'static BlockTables {
    static T: OnceLock<BlockTables> = OnceLock::new();
    T.get_or_init(|| {
        let mut t = BlockTables {
            vlc_tbl0: [0; 1024],
            vlc_tbl1: [0; 1024],
            uvlc_tbl0: [0; 256 + 64],
            uvlc_tbl1: [0; 256],
            uvlc_tbl1_wide: vec![0; 4096],
            uvlc_bias: [0; 256 + 64],
        };
        vlc_init_table(&mut t.vlc_tbl0, &TBL0);
        vlc_init_table(&mut t.vlc_tbl1, &TBL1);
        uvlc_init_tables(&mut t);
        uvlc_init_wide_table(&mut t.uvlc_tbl1_wide);
        t
    })
}

/// Port of `vlc_init_tables` (external/OpenJPH/src/core/coding/ojph_block_common.cpp:124-190
/// @ OpenJPH 0.32.0), for one table: each 10-bit index (a 3-bit context and 7 bits of
/// codeword) gets the fields of the last source row whose context and codeword match.
fn vlc_init_table(tbl: &mut [u16; 1024], src: &[[u8; 7]]) {
    for (i, e) in tbl.iter_mut().enumerate() {
        let cwd = (i & 0x7F) as u32; // from i extract codeword
        let c_q = (i >> 7) as u32; // from i extract context
        for r in src {
            let [rc_q, rho, u_off, e_k, e_1, rcwd, cwd_len] = r.map(u32::from);
            if rc_q == c_q && rcwd == (cwd & ((1 << cwd_len) - 1)) {
                *e = ((rho << 4) | (u_off << 3) | (e_k << 12) | (e_1 << 8) | cwd_len) as u16;
            }
        }
    }
}

/// The prefix codewords (`dec`): the prefix length, the suffix length and the prefix value.
#[allow(clippy::identity_op)] // as upstream spells them
const DEC: [u32; 8] = [
    3 | (5 << 2) | (5 << 5), // 000 == 000, prefix codeword "000"
    1 | (0 << 2) | (1 << 5), // 001 == xx1, prefix codeword "1"
    2 | (0 << 2) | (2 << 5), // 010 == x10, prefix codeword "01"
    1 | (0 << 2) | (1 << 5), // 011 == xx1, prefix codeword "1"
    3 | (1 << 2) | (3 << 5), // 100 == 100, prefix codeword "001"
    1 | (0 << 2) | (1 << 5), // 101 == xx1, prefix codeword "1"
    2 | (0 << 2) | (2 << 5), // 110 == x10, prefix codeword "01"
    1 | (0 << 2) | (1 << 5), // 111 == xx1, prefix codeword "1"
];

#[inline]
fn pack(total_prefix: u32, total_suffix: u32, u0_suffix_len: u32, u0: u32, u1: u32) -> u16 {
    (total_prefix | (total_suffix << 3) | (u0_suffix_len << 7) | (u0 << 10) | (u1 << 13)) as u16
}

/// Port of `uvlc_init_tables` (external/OpenJPH/src/core/coding/ojph_block_common.cpp:196-337
/// @ OpenJPH 0.32.0).
fn uvlc_init_tables(t: &mut BlockTables) {
    for i in 0..(256 + 64) as u32 {
        let mode = i >> 6;
        let mut vlc = i & 0x3F;
        if mode == 0 {
            // both u_off are 0
            t.uvlc_tbl0[i as usize] = 0;
            t.uvlc_bias[i as usize] = 0;
        } else if mode <= 2 {
            // u_off are either 01 or 10
            let d = DEC[(vlc & 0x7) as usize]; // look at the least significant 3 bits
            let total_prefix = d & 0x3;
            let total_suffix = (d >> 2) & 0x7;
            let u0_suffix_len = if mode == 1 { total_suffix } else { 0 };
            let u0 = if mode == 1 { d >> 5 } else { 0 };
            let u1 = if mode == 1 { 0 } else { d >> 5 };
            t.uvlc_tbl0[i as usize] = pack(total_prefix, total_suffix, u0_suffix_len, u0, u1);
        } else if mode == 3 {
            // both u_off are 1, and MEL event is 0
            let d0 = DEC[(vlc & 0x7) as usize]; // LSBs of VLC are prefix codeword
            vlc >>= d0 & 0x3; // Consume bits
            let d1 = DEC[(vlc & 0x7) as usize]; // LSBs of VLC are prefix codeword
            let (total_prefix, u0_suffix_len, total_suffix, u0, u1);
            if (d0 & 0x3) == 3 {
                total_prefix = (d0 & 0x3) + 1;
                u0_suffix_len = (d0 >> 2) & 0x7;
                total_suffix = u0_suffix_len;
                u0 = d0 >> 5;
                u1 = (vlc & 1) + 1;
                t.uvlc_bias[i as usize] = 4; // 0b00 for u0 and 0b01 for u1
            } else {
                total_prefix = (d0 & 0x3) + (d1 & 0x3);
                u0_suffix_len = (d0 >> 2) & 0x7;
                total_suffix = u0_suffix_len + ((d1 >> 2) & 0x7);
                u0 = d0 >> 5;
                u1 = d1 >> 5;
                t.uvlc_bias[i as usize] = 0;
            }
            t.uvlc_tbl0[i as usize] = pack(total_prefix, total_suffix, u0_suffix_len, u0, u1);
        } else if mode == 4 {
            // both u_off are 1, and MEL event is 1
            let d0 = DEC[(vlc & 0x7) as usize];
            vlc >>= d0 & 0x3;
            let d1 = DEC[(vlc & 0x7) as usize];
            let total_prefix = (d0 & 0x3) + (d1 & 0x3);
            let u0_suffix_len = (d0 >> 2) & 0x7;
            let total_suffix = u0_suffix_len + ((d1 >> 2) & 0x7);
            let u0 = (d0 >> 5) + 2;
            let u1 = (d1 >> 5) + 2;
            t.uvlc_tbl0[i as usize] = pack(total_prefix, total_suffix, u0_suffix_len, u0, u1);
            t.uvlc_bias[i as usize] = 10; // 0b10 for u0 and 0b10 for u1
        }
    }

    for i in 0..256u32 {
        let mode = i >> 6;
        let mut vlc = i & 0x3F;
        if mode == 0 {
            // both u_off are 0
            t.uvlc_tbl1[i as usize] = 0;
        } else if mode <= 2 {
            // u_off are either 01 or 10
            let d = DEC[(vlc & 0x7) as usize]; // look at the 3 LSB bits
            let total_prefix = d & 0x3;
            let total_suffix = (d >> 2) & 0x7;
            let u0_suffix_len = if mode == 1 { total_suffix } else { 0 };
            let u0 = if mode == 1 { d >> 5 } else { 0 };
            let u1 = if mode == 1 { 0 } else { d >> 5 };
            t.uvlc_tbl1[i as usize] = pack(total_prefix, total_suffix, u0_suffix_len, u0, u1);
        } else if mode == 3 {
            // both u_off are 1
            let d0 = DEC[(vlc & 0x7) as usize];
            vlc >>= d0 & 0x3;
            let d1 = DEC[(vlc & 0x7) as usize];
            let total_prefix = (d0 & 0x3) + (d1 & 0x3);
            let u0_suffix_len = (d0 >> 2) & 0x7;
            let total_suffix = u0_suffix_len + ((d1 >> 2) & 0x7);
            let u0 = d0 >> 5;
            let u1 = d1 >> 5;
            t.uvlc_tbl1[i as usize] = pack(total_prefix, total_suffix, u0_suffix_len, u0, u1);
        }
    }
}

/// Port of `uvlc_init_wide_table`
/// (external/OpenJPH/src/core/coding/ojph_block_common.cpp:346-416 @ OpenJPH 0.32.0): the UVLC
/// table of non-initial rows over 10 bits of codeword; an entry packs the bits used and both
/// u values, or 0x1F when they take more than 10 bits.
fn uvlc_init_wide_table(tbl: &mut [u32]) {
    for idx in 0..4096u32 {
        let mode = idx >> 10; // 2 bits
        let vlc = idx & 0x3FF; // 10 bits
        if mode == 0 {
            tbl[idx as usize] = 0;
            continue;
        }
        if mode <= 2 {
            // single UVLC (one u_off set)
            let d = DEC[(vlc & 0x7) as usize];
            let prefix_len = d & 0x3;
            let suffix_len = (d >> 2) & 0x7;
            let u_pfx = d >> 5;
            let suffix_val = (vlc >> prefix_len) & ((1u32 << suffix_len) - 1);
            let u_val = u_pfx + suffix_val;
            let total = prefix_len + suffix_len;
            let u_q0 = if mode == 1 { u_val } else { 0 };
            let u_q1 = if mode == 2 { u_val } else { 0 };
            tbl[idx as usize] = total | (u_q0 << 5) | (u_q1 << 13);
            continue;
        }
        let d0 = DEC[(vlc & 0x7) as usize];
        let p0_len = d0 & 0x3;
        let s0_len = (d0 >> 2) & 0x7;
        let u0_pfx = d0 >> 5;
        let vlc1 = vlc >> p0_len; // consume prefix0
        let d1 = DEC[(vlc1 & 0x7) as usize];
        let p1_len = d1 & 0x3;
        let s1_len = (d1 >> 2) & 0x7;
        let u1_pfx = d1 >> 5;
        let total_prefix = p0_len + p1_len;
        let total_suffix = s0_len + s1_len;
        let total = total_prefix + total_suffix;
        if total > 10 {
            tbl[idx as usize] = 0x1F; // fallback sentinel
            continue;
        }
        let suffix_bits = vlc >> total_prefix;
        let s0_val = suffix_bits & ((1u32 << s0_len) - 1);
        let s1_val = (suffix_bits >> s0_len) & ((1u32 << s1_len) - 1);
        let u_q0 = u0_pfx + s0_val;
        let u_q1 = u1_pfx + s1_val;
        tbl[idx as usize] = total | (u_q0 << 5) | (u_q1 << 13);
    }
}

